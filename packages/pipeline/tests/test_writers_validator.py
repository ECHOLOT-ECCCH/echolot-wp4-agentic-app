from __future__ import annotations

import copy
import io
import json
from pathlib import Path

from lxml import etree

from elexifier_pipeline.dmlex import validator, writers
from elexifier_pipeline.dmlex.schema import DMLEX_NS
from elexifier_pipeline.xml import dmlexifier as dx
from elexifier_pipeline.xml import streaming

NS = "http://elex.is/wp1/teiLex0Mapper/meta"


def _convert(mapping: dict, path: Path) -> tuple[dict, list[dict], dx.TEltDesc]:
    desc = dx.load_mapping(mapping)
    resource = dx.TransformEx(mappingEltDesc=desc, fnOrFileList=[path])[0]
    return writers.resource_scalars(resource, desc), writers.entries_of(resource, desc), desc


def test_oxford_xml_validates(oxford_mapping: dict, samples: dict, tmp_path: Path) -> None:
    scalars, entries, _ = _convert(oxford_mapping, samples["oxford"])
    out = tmp_path / "oxford.dmlex.xml"
    with out.open("wb") as fh:
        report = writers.write_xml(fh, scalars, entries)
    assert report.entries == 102
    assert report.warnings == []
    result = validator.validate_xml(out)
    assert result.valid, result.errors[:5]
    root = etree.parse(str(out)).getroot()
    assert root.tag == f"{{{DMLEX_NS}}}lexicographicResource"
    assert root.get("uri") == "http://example.org/oxford-sample"
    first = root[0]
    assert [etree.QName(c).localname for c in first] == [
        "headword",
        "partOfSpeech",
        "pronunciation",
        "sense",
    ]
    headword = first.find(f"{{{DMLEX_NS}}}headword")
    assert headword is not None and headword.text == "azyme"


def test_streamed_entries_write_and_validate(
    oxford_mapping: dict, samples: dict, tmp_path: Path
) -> None:
    desc = dx.load_mapping(oxford_mapping)
    plan = streaming.plan_for(desc)
    out = tmp_path / "streamed.xml"
    entries = streaming.stream_transform(samples["oxford"], desc, plan=plan)
    with out.open("wb") as fh:
        first_entries = []

        def tee():
            for e in entries:
                first_entries.append(e) if len(first_entries) < 1 else None
                yield e

        report = writers.write_xml(fh, {"uri": "urn:x", "langCode": "en", "title": "t"}, tee())
    # resource scalars are only known after the first entry with streaming; here we passed them
    assert report.entries == 102
    assert validator.validate_xml(out).valid
    assert first_entries[0]["headword"] == "azyme"


def test_kks_owner_mapping_reports_schema_problems(
    kks_mapping: dict, samples: dict, tmp_path: Path
) -> None:
    scalars, entries, _ = _convert(kks_mapping, samples["kks"])
    out = tmp_path / "kks.xml"
    with out.open("wb") as fh:
        report = writers.write_xml(fh, scalars, entries)
    assert any("'language' is not a member" in w for w in report.warnings)
    result = validator.validate_xml(out, max_errors=10)
    assert not result.valid
    reasons = " ".join(e.reason for e in result.errors)
    assert "langCode" in reasons or "id" in reasons
    assert result.truncated is True
    assert result.errors[0].entry_index is None or result.errors[0].entry_index >= 0


def test_kks_mapping_fixed_validates(kks_mapping: dict, samples: dict, tmp_path: Path) -> None:
    fixed = copy.deepcopy(kks_mapping)
    for tv in fixed["textVals"]:
        if tv["outElement"] == "language":
            tv["outElement"] = "langCode"
            tv["constant"] = "krl"
    entry = fixed["children"][0]
    for child in entry["children"]:
        if child["outElement"] == "partOfSpeech":  # a few source elements have no value
            child["inSelector"] += "[@value]"
        if child["outElement"] == "sense":
            child["textVals"] = [{"attribute": f"{{{NS}}}autogenerated", "outElement": "id"}]
            for grandchild in child["children"]:
                if grandchild["outElement"] == "example":  # some fragments are empty in the source
                    grandchild["inSelector"] += "[normalize-space()]"
    scalars, entries, _ = _convert(fixed, samples["kks"])
    out = tmp_path / "kks-fixed.xml"
    with out.open("wb") as fh:
        report = writers.write_xml(fh, scalars, entries)
    assert report.warnings == []
    assert report.dropped_duplicates.get("partOfSpeech", 0) > 0  # repeated identical POS tags
    result = validator.validate_xml(out)
    # What remains are duplicate headwords with the same part of speech: DMLex wants homograph
    # numbers for those, which the conversion run will assign (M1.8, two-pass streaming).
    assert all("entryUnique" in e.reason for e in result.errors), result.errors[:5]
    assert 0 < result.error_count < 10
    assert result.limitation_count > 0  # entries with two parts of speech trip the XSD uniqueness
    assert "cannot evaluate" in result.summary()
    assert entries[2]["senses"][0]["id"] == "entry.id.3.sense.id.1"


def test_markers_are_inlined() -> None:
    entry = {
        "id": "e1",
        "headword": "take sb in",
        "placeholderMarkers": [{"startIndex": 5, "endIndex": 7}],
        "senses": [
            {
                "id": "s1",
                "definitions": [
                    {
                        "text": "to run quickly, run again",
                        "headwordMarkers": [{"startIndex": 3, "endIndex": 6}],
                        "collocateMarkers": [
                            {"startIndex": 20, "endIndex": 25, "lemma": "again", "id": "c1"}
                        ],
                    }
                ],
                "examples": [
                    {
                        "text": "run and run",
                        "headwordMarkers": [
                            {"startIndex": 0, "endIndex": 3},
                            {"startIndex": 8, "endIndex": 11},
                        ],
                    }
                ],
            }
        ],
    }
    element = writers.entry_element(entry)
    xml = etree.tostring(element, encoding="unicode")
    assert xml.startswith(f'<entry xmlns="{DMLEX_NS}" id="e1">')
    assert "<headword>take <placeholderMarker>sb</placeholderMarker> in</headword>" in xml
    assert (
        "to <headwordMarker>run</headwordMarker> quickly, run "
        '<collocateMarker lemma="again" id="c1">again</collocateMarker>'
    ) in xml
    assert (
        "<text><headwordMarker>run</headwordMarker> and <headwordMarker>run</headwordMarker></text>"
    ) in xml
    buf = io.BytesIO()
    writers.write_xml(buf, {"uri": "urn:t", "langCode": "en"}, [entry])
    assert validator.validate_xml(io.BytesIO(buf.getvalue())).valid


def test_json_writer_and_consistency(oxford_mapping: dict, samples: dict) -> None:
    scalars, entries, _ = _convert(oxford_mapping, samples["oxford"])
    buf = io.StringIO()
    count = writers.write_json(buf, scalars, entries)
    data = json.loads(buf.getvalue())
    assert count == 102 and len(data["entries"]) == 102
    assert data["title"] == "Oxford English-Slovene sample"
    assert data["entries"][1]["partsOfSpeech"] == [{"tag": "noun"}]
    issues = validator.check_consistency(entries)
    assert not [
        i
        for i in issues
        if i.code in ("duplicate-entry-id", "duplicate-sense-id", "empty-headword")
    ]
    broken = [
        {
            "id": "a",
            "headword": "",
            "senses": [{"id": "s"}, {"id": "s", "definitions": [{"text": ""}]}],
        },
        {"id": "a", "headword": "x", "partsOfSpeech": [{"tag": ""}]},
    ]
    codes = sorted({i.code for i in validator.check_consistency(broken)})
    assert codes == [
        "duplicate-entry-id",
        "duplicate-sense-id",
        "empty-definition",
        "empty-headword",
        "empty-pos",
        "empty-sense",
    ]


def test_validate_entries_attributes_findings(oxford_mapping: dict, samples: dict) -> None:
    desc = dx.load_mapping(oxford_mapping)
    plan = streaming.plan_for(desc)
    entries = list(streaming.stream_transform(samples["oxford"], desc, plan=plan, limit=12))
    entries[3] = dict(entries[3], headword="")  # break one entry
    entries[5] = dict(entries[5], senses=[{"id": "dup"}, {"id": "dup", "indicator": "x"}])
    result = validator.validate_entries(plan.resource_scalars, entries)
    assert not result.report.valid
    assert {3, 5} <= set(result.per_entry)
    codes = {i.code for i in result.issues_for(3)}
    assert "empty-headword" in codes and "schema" in codes  # XSD assert + consistency
    assert any(i.code == "duplicate-sense-id" for i in result.issues_for(5))
    assert all(i.path.startswith(("sense", "entry", "headword")) for i in result.issues_for(5))
    assert result.resource_issues == []

    # missing resource values get placeholders and a resource-level warning
    result = validator.validate_entries({}, entries[:2])
    assert [i.code for i in result.resource_issues] == ["missing-resource-value"] * 2
    assert result.report.valid and result.per_entry == {}
