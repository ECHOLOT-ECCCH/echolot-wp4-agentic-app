from __future__ import annotations

import copy

import pytest

from elexifier_pipeline.dmlex import schema
from elexifier_pipeline.xml import mapping as mp
from elexifier_pipeline.xml.dmlexifier import MappingError

NS = "http://elex.is/wp1/teiLex0Mapper/meta"


def _errors(issues: list[mp.Issue]) -> list[str]:
    return [i.message for i in issues if i.severity == "error"]


def test_owner_mappings_load_and_check(kks_mapping: dict, oxford_mapping: dict) -> None:
    kks = mp.load_mapping_spec(kks_mapping)
    issues = mp.check_mapping(kks)
    # the owner's KKS mapping has 'language' instead of 'langCode' and no sense ids
    messages = _errors(issues)
    assert any("'language' is not a member" in m for m in messages)
    assert any("needs a 'langCode'" in m for m in messages)
    assert any("a sense needs an 'id'" in m for m in messages)
    oxford = mp.load_mapping_spec(oxford_mapping)
    assert not _errors(mp.check_mapping(oxford)), mp.check_mapping(oxford)


def test_unknown_keys_and_missing_fields_are_rejected() -> None:
    with pytest.raises(MappingError, match="Extra inputs"):
        mp.load_mapping_spec({"inSelector": "/d", "outElement": "entry", "bogus": 1})
    with pytest.raises(MappingError, match="inSelector"):
        mp.load_mapping_spec({"outElement": "entry"})


def test_checks_catch_bad_xpath_regex_and_vocabulary() -> None:
    spec = mp.load_mapping_spec(
        {
            "inSelector": "/d",
            "outElement": "lexicographicResource",
            "textVals": [
                {"attribute": f"{{{NS}}}constant", "constant": "u", "outElement": "uri"},
                {"attribute": f"{{{NS}}}constant", "constant": "en", "outElement": "langCode"},
            ],
            "children": [
                {
                    "inSelector": "e[",
                    "outElement": "entry",
                    "textVals": [
                        {
                            "inSelector": "w",
                            "attribute": f"{{{NS}}}innerText",
                            "outElement": "headword",
                            "regex": "(",
                        },
                        {"attribute": f"{{{NS}}}autogenerated", "outElement": "id"},
                        {"attribute": f"{{{NS}}}innerText", "outElement": "gloss"},
                    ],
                    "children": [
                        {"inSelector": "x", "outElement": "translation", "textVals": []},
                        {
                            "inSelector": "s",
                            "outElement": "sense",
                            "textVals": [],
                            "children": [
                                {
                                    "inSelector": "d",
                                    "outElement": "entry",
                                    "textVals": [{"attribute": "a", "outElement": "headword"}],
                                }
                            ],
                        },
                    ],
                }
            ],
        }
    )
    messages = _errors(mp.check_mapping(spec))
    assert any("inSelector XPath is invalid" in m for m in messages)
    assert any("regex is invalid" in m for m in messages)
    assert any("'gloss' is not a member of 'entry'" in m for m in messages)
    assert any("'translation' is not a DMLex object element" in m for m in messages)
    assert any("'entry' cannot be a child of 'sense'" in m for m in messages)
    assert any("a sense needs an 'id'" in m for m in messages)


def test_summary_and_json_schema(oxford_mapping: dict) -> None:
    spec = mp.load_mapping_spec(oxford_mapping)
    text = mp.summarize(spec)
    assert text.splitlines()[0] == "lexicographicResource <- /oxford"
    assert "  entry <- se" in text
    assert ".headword = text (with descendants) of hw" in text
    assert "value translations" in text
    json_schema = mp.mapping_json_schema()
    root = json_schema["$defs"]["EltDesc"]  # recursive model: the root is a reference
    assert root["additionalProperties"] is False
    assert set(json_schema["$defs"]) == {"EltDesc", "MarkerDesc", "TextValDesc"}


def test_round_trip_to_converter_descriptor(oxford_mapping: dict) -> None:
    spec = mp.load_mapping_spec(oxford_mapping)
    desc = spec.to_desc()
    assert desc.outElement == "lexicographicResource"
    assert desc.find("entry") is not None
    changed = copy.deepcopy(oxford_mapping)
    changed["children"][0]["textVals"] = changed["children"][0]["textVals"][1:]  # drop headword
    assert any(
        "needs a 'headword'" in m for m in _errors(mp.check_mapping(mp.load_mapping_spec(changed)))
    )


def test_schema_knowledge() -> None:
    entry = schema.element_spec("entry")
    assert entry is not None
    assert [c.name for c in entry.children][:3] == ["headword", "partOfSpeech", "label"]
    assert entry.members() == {"headword", "id", "homographNumber"}
    assert schema.plural_of("entry") == "entries"
    assert schema.plural_of("partOfSpeech") == "partsOfSpeech"
    assert schema.plural_of("sense") == "senses"
    assert "headword" not in schema.object_names()
    assert {"entry", "sense", "definition", "example", "label"} <= schema.object_names()


def test_translations_need_lang_code_without_translation_language() -> None:
    spec = {
        "inSelector": "/d",
        "outElement": "lexicographicResource",
        "textVals": [
            {"attribute": f"{{{NS}}}constant", "constant": "u", "outElement": "uri"},
            {"attribute": f"{{{NS}}}constant", "constant": "en", "outElement": "langCode"},
        ],
        "children": [
            {
                "inSelector": "e",
                "outElement": "entry",
                "textVals": [{"attribute": f"{{{NS}}}innerText", "outElement": "headword"}],
                "children": [
                    {
                        "inSelector": "s",
                        "outElement": "sense",
                        "textVals": [{"attribute": f"{{{NS}}}autogenerated", "outElement": "id"}],
                        "children": [
                            {
                                "inSelector": "gl",
                                "outElement": "headwordExplanation",
                                "textVals": [
                                    {"attribute": f"{{{NS}}}innerText", "outElement": "text"}
                                ],
                            }
                        ],
                    }
                ],
            }
        ],
    }
    errors = _errors(mp.check_mapping(mp.load_mapping_spec(spec)))
    assert any("headwordExplanation" in e and "langCode" in e for e in errors)

    with_language = copy.deepcopy(spec)
    with_language["children"].append(
        {
            "inSelector": ".",
            "outElement": "translationLanguage",
            "textVals": [
                {"attribute": f"{{{NS}}}constant", "constant": "sl", "outElement": "langCode"}
            ],
        }
    )
    errors = _errors(mp.check_mapping(mp.load_mapping_spec(with_language)))
    assert not any("headwordExplanation" in e for e in errors)
