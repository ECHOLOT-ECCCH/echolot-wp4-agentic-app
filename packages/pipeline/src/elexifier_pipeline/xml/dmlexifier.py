"""Mapping-driven XML to DMLex converter (vendored from the project owner's ``dmlexifier.py``).

A mapping is a tree of element descriptors (``TEltDesc``) whose ``inSelector`` XPath expressions
select source elements; each descriptor produces one output object per match, with ``textVals``
(``TTextValDesc``) filling scalar members from inner text, attributes, constants or generated ids,
optionally through a regex and an ``xlat`` value map, and ``children`` producing nested lists.

Changes against the original script (see docs/DECISIONS.md, 2026-09-16):
- no web-service dependencies, no module-level logging configuration;
- the marker ``inSelector`` attribute typo is fixed;
- generated ids are hierarchical (``entry.id.3``, ``entry.id.3.sense.id.2``) so nested ids are
  unique document-wide, matching the owner's later conversions;
- ``transform_element`` applies a descriptor to one already-parsed element, which is what the
  streaming converter in :mod:`elexifier_pipeline.xml.streaming` uses;
- XML serialisation of the result moved to :mod:`elexifier_pipeline.dmlex.writers`.
"""

from __future__ import annotations

import json
import logging
import re
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from lxml import etree

log = logging.getLogger(__name__)

NS_META = "http://elex.is/wp1/teiLex0Mapper/meta"
ATTR_INNER_TEXT = f"{{{NS_META}}}innerText"
ATTR_INNER_TEXT_REC = f"{{{NS_META}}}innerTextRec"
ATTR_CONSTANT = f"{{{NS_META}}}constant"
ATTR_AUTO = f"{{{NS_META}}}autogenerated"
META_ATTRIBUTES = (ATTR_INNER_TEXT, ATTR_INNER_TEXT_REC, ATTR_CONSTANT, ATTR_AUTO)

ElementType = type(etree.Element("x"))

JsonDict = dict[str, Any]


class MappingError(ValueError):
    """The mapping description is malformed."""


class TMarkerDesc:
    __slots__ = [
        "compiledRegex",
        "inSelector",
        "jsonPlural",
        "namespaces",
        "outElement",
        "regex",
        "regexGroup",
    ]

    def __init__(self, jsonDesc: JsonDict) -> None:
        self.inSelector: str | None = jsonDesc.get("inSelector")
        self.outElement: str = _required(jsonDesc, "outElement", "marker")
        self.jsonPlural: str = jsonDesc.get("jsonPlural", self.outElement + "s")
        self.regex: str | None = jsonDesc.get("regex")
        self.compiledRegex = None if self.regex is None else _compile(self.regex)
        self.regexGroup: int | str | None = jsonDesc.get("regexGroup")
        self.namespaces: dict[str, str] | None = jsonDesc.get("namespaces")


class TTextValDesc:
    __slots__ = [
        "attribute",
        "compiledRegex",
        "constant",
        "excludeSelector",
        "inSelector",
        "markers",
        "namespaces",
        "normalizeWhitespace",
        "outElement",
        "regex",
        "regexGroup",
        "xlat",
    ]

    def __init__(self, jsonDesc: JsonDict) -> None:
        # XPath relative to the element of the owning TEltDesc; if omitted, that element is used.
        self.inSelector: str | None = jsonDesc.get("inSelector")
        self.namespaces: dict[str, str] | None = jsonDesc.get("namespaces")
        self.attribute: str = _required(jsonDesc, "attribute", "textVal")
        self.constant: str = jsonDesc.get("constant", "")
        self.regex: str | None = jsonDesc.get("regex")
        self.compiledRegex = None if self.regex is None else _compile(self.regex)
        self.regexGroup: int | str | None = jsonDesc.get("regexGroup")
        self.outElement: str = _required(jsonDesc, "outElement", "textVal")
        self.xlat: dict[str, str] | None = jsonDesc.get("xlat") or None
        markersDesc = jsonDesc.get("markers")
        self.markers: list[TMarkerDesc] | None = (
            None if markersDesc is None else [TMarkerDesc(m) for m in markersDesc]
        )
        # Platform extensions (docs/PLAN.md 7.8b): skip sub-elements when building inner text,
        # and collapse whitespace runs. Both are ignored by the original script.
        self.excludeSelector: str | None = jsonDesc.get("excludeSelector")
        self.normalizeWhitespace: bool = bool(jsonDesc.get("normalizeWhitespace", False))


class TEltDesc:
    __slots__ = [
        "children",
        "copyToOutElt",
        "inSelector",
        "jsonPlural",
        "namespaces",
        "outElement",
        "textVals",
    ]

    def __init__(self, jsonDesc: JsonDict | None) -> None:
        if jsonDesc is None:
            return
        self.inSelector: str = _required(jsonDesc, "inSelector", "element")
        self.outElement: str = _required(jsonDesc, "outElement", "element")
        self.jsonPlural: str = jsonDesc.get("jsonPlural", self.outElement + "s")
        self.namespaces: dict[str, str] | None = jsonDesc.get("namespaces")
        childDescs = jsonDesc.get("children")
        self.children: list[TEltDesc] | None = (
            None if not childDescs else [TEltDesc(c) for c in childDescs]
        )
        textDescs = jsonDesc.get("textVals")
        self.textVals: list[TTextValDesc] | None = (
            None if not textDescs else [TTextValDesc(t) for t in textDescs]
        )
        self.copyToOutElt: JsonDict | None = jsonDesc.get("copyToOutElt")

    def find(self, outElement: str) -> TEltDesc | None:
        """First descriptor (depth first) producing ``outElement``."""
        if self.outElement == outElement:
            return self
        for child in self.children or []:
            found = child.find(outElement)
            if found is not None:
                return found
        return None


def _required(desc: JsonDict, key: str, kind: str) -> Any:
    try:
        return desc[key]
    except KeyError as exc:
        raise MappingError(f"{kind} descriptor is missing '{key}'") from exc


def xpath_nodes(
    context: etree._Element | etree._ElementTree, expr: str, namespaces: dict[str, str] | None
) -> list[Any]:
    """Evaluate an XPath that is expected to return nodes; scalars become a one-item list."""
    result = context.xpath(expr, namespaces=namespaces)
    if isinstance(result, list):
        return result
    return [result]


def _compile(pattern: str) -> re.Pattern[str]:
    try:
        return re.compile(pattern)
    except re.error as exc:
        raise MappingError(f"invalid regex {pattern!r}: {exc}") from exc


def load_mapping(source: JsonDict | str | Path) -> TEltDesc:
    """Build the descriptor tree from a dict, a JSON string, or a path to a JSON file."""
    if isinstance(source, dict):
        return TEltDesc(source)
    if isinstance(source, Path):
        return TEltDesc(json.loads(source.read_text(encoding="utf-8")))
    text = source.strip()
    if text.startswith("{"):
        return TEltDesc(json.loads(text))
    return TEltDesc(json.loads(Path(text).read_text(encoding="utf-8")))


# --- inner text with element positions -------------------------------------------------------


def BuildInnerText(
    elt: etree._Element,
    startPos: dict[int, int],
    endPos: dict[int, int],
    recurse: bool,
    keepAlive: list[etree._Element] | None = None,
    excluded: set[int] | None = None,
) -> str:
    """Inner text of ``elt`` (descendants included when ``recurse``); ``startPos``/``endPos``
    receive, per descendant id, the character span its content occupies in the result.

    ``keepAlive`` must hold the descendant proxies while the positions are used: lxml recreates
    proxy objects on demand, so ``id()`` is only stable for proxies that are still referenced.
    Elements whose id is in ``excluded`` contribute nothing (their tails still do).
    """
    outList: list[str] = []
    curPos = 0
    keep = keepAlive if keepAlive is not None else []
    skip = excluded or set()

    def Rec(e: etree._Element) -> None:
        nonlocal curPos
        if e.text:
            outList.append(e.text)
            curPos += len(e.text)
        for child in e:
            keep.append(child)
            if not isinstance(child.tag, str) or id(child) in skip:
                if child.tail:
                    outList.append(child.tail)
                    curPos += len(child.tail)
                continue
            startPos[id(child)] = curPos
            if recurse:
                Rec(child)
            endPos[id(child)] = curPos
            if child.tail:
                outList.append(child.tail)
                curPos += len(child.tail)

    Rec(elt)
    return "".join(outList)


_WS = re.compile(r"\s+")


def normalize_whitespace(text: str) -> str:
    return _WS.sub(" ", text).strip()


# --- transformation --------------------------------------------------------------------------


class _Transformer:
    """Applies descriptors to elements; keeps the generated-id counters for one document."""

    def __init__(self) -> None:
        self.autogenCounters: dict[str, int] = {}

    def next_id(self, parentId: str | None, eltDesc: TEltDesc, textDesc: TTextValDesc) -> str:
        key = f"{eltDesc.outElement}.{textDesc.outElement}"
        scope = f"{parentId}.{key}" if parentId else key
        seqNo = self.autogenCounters.get(scope, 0) + 1
        self.autogenCounters[scope] = seqNo
        return f"{scope}.{seqNo}"

    def process_text(
        self,
        xmlElt: etree._Element,
        outElt: JsonDict,
        eltDesc: TEltDesc,
        textDesc: TTextValDesc,
        parentId: str | None,
    ) -> None:
        if textDesc.inSelector is not None:
            matches = xpath_nodes(xmlElt, textDesc.inSelector, textDesc.namespaces)
            if not matches:
                return
            xmlElt = matches[0]
        eltStartPos: dict[int, int] = {}
        eltEndPos: dict[int, int] = {}
        keepAlive: list[etree._Element] = []
        if textDesc.attribute == ATTR_CONSTANT:
            attrValue = textDesc.constant
        elif textDesc.attribute == ATTR_AUTO:
            attrValue = self.next_id(parentId, eltDesc, textDesc)
        elif textDesc.attribute in (ATTR_INNER_TEXT, ATTR_INNER_TEXT_REC):
            if not isinstance(xmlElt, ElementType):  # xpath returned an attribute or text node
                attrValue = str(xmlElt)
            else:
                excluded: set[int] = set()
                if textDesc.excludeSelector:
                    for node in xpath_nodes(xmlElt, textDesc.excludeSelector, textDesc.namespaces):
                        keepAlive.append(node)
                        excluded.add(id(node))
                attrValue = BuildInnerText(
                    xmlElt,
                    eltStartPos,
                    eltEndPos,
                    textDesc.attribute == ATTR_INNER_TEXT_REC,
                    keepAlive,
                    excluded,
                )
        else:
            attrValue = (
                xmlElt.attrib.get(textDesc.attribute) if isinstance(xmlElt, ElementType) else None
            )
            if attrValue is None:
                return
        if textDesc.compiledRegex is None:
            matchStart, matchEnd = 0, len(attrValue)
        else:
            m = textDesc.compiledRegex.search(attrValue)
            if not m:
                return
            grp = 0 if textDesc.regexGroup is None else textDesc.regexGroup
            try:
                matchStart, matchEnd = m.start(grp), m.end(grp)
            except (IndexError, error_types()):
                matchStart, matchEnd = m.start(0), m.end(0)
            if matchStart < 0 or matchEnd < 0:
                return
        matchLen = matchEnd - matchStart
        outValue = attrValue[matchStart:matchEnd]
        if textDesc.normalizeWhitespace and not textDesc.markers:
            outValue = normalize_whitespace(outValue)
            if not outValue:
                return
        outElt[textDesc.outElement] = (
            outValue if not textDesc.xlat else textDesc.xlat.get(outValue, outValue)
        )
        if textDesc.markers:
            for markerDesc in textDesc.markers:
                ranges: list[tuple[int, int]] = []
                if not markerDesc.inSelector:
                    ranges = [(0, matchLen)]
                elif isinstance(xmlElt, ElementType):
                    for markerElt in xpath_nodes(
                        xmlElt, markerDesc.inSelector, markerDesc.namespaces
                    ):
                        idxFrom = eltStartPos.get(id(markerElt), -1)
                        idxTo = eltEndPos.get(id(markerElt), -1)
                        if idxFrom < 0 or idxTo < 0:
                            continue
                        if idxTo <= matchStart or idxFrom >= matchEnd:
                            continue  # does not overlap the matched part
                        ranges.append(
                            (max(idxFrom - matchStart, 0), min(idxTo - matchStart, matchLen))
                        )
                if markerDesc.compiledRegex is not None:
                    searched, ranges = ranges, []
                    for idxFrom, idxTo in searched:
                        for m2 in markerDesc.compiledRegex.finditer(outValue[idxFrom:idxTo]):
                            grp2 = 0 if markerDesc.regexGroup is None else markerDesc.regexGroup
                            try:
                                s2, e2 = m2.start(grp2), m2.end(grp2)
                            except (IndexError, error_types()):
                                continue
                            if s2 < 0 or e2 < 0:
                                continue
                            ranges.append((idxFrom + s2, idxFrom + e2))
                ranges = sorted(set(ranges))
                outList = outElt.get(markerDesc.jsonPlural, [])
                outList.extend({"startIndex": a, "endIndex": b} for a, b in ranges)
                outElt[markerDesc.jsonPlural] = outList

    def process_elt(
        self, context: etree._Element | etree._ElementTree, eltDesc: TEltDesc, parentId: str | None
    ) -> list[JsonDict]:
        outListJson: list[JsonDict] = []
        for xmlElt in xpath_nodes(context, eltDesc.inSelector, eltDesc.namespaces):
            outJsonElt: JsonDict = {}
            # text values first so that a generated id is available to the children
            if eltDesc.textVals:
                for textDesc in eltDesc.textVals:
                    self.process_text(xmlElt, outJsonElt, eltDesc, textDesc, parentId)
            ownId = outJsonElt.get("id")
            ownId = str(ownId) if ownId is not None else parentId
            if eltDesc.children:
                for childDesc in eltDesc.children:
                    childJsonList = self.process_elt(xmlElt, childDesc, ownId)
                    if childJsonList:
                        outJsonElt.setdefault(childDesc.jsonPlural, []).extend(childJsonList)
            if eltDesc.copyToOutElt:
                outJsonElt.update(eltDesc.copyToOutElt)
            outListJson.append(outJsonElt)
        return outListJson


def error_types() -> type[Exception]:
    return re.error


def TransformSingleXmlDoc(xmlTree: etree._ElementTree, mainEltDesc: TEltDesc) -> list[JsonDict]:
    """Apply the mapping to a parsed document; returns one JSON-like dict per root match."""
    return _Transformer().process_elt(xmlTree, mainEltDesc, None)


def transform_element(
    element: etree._Element,
    eltDesc: TEltDesc,
    transformer: _Transformer | None = None,
    parentId: str | None = None,
) -> list[JsonDict]:
    """Apply ``eltDesc`` with ``element`` as the XPath context (used by the streaming converter)."""
    return (transformer or _Transformer()).process_elt(element, eltDesc, parentId)


def new_transformer() -> _Transformer:
    return _Transformer()


def ExtractEntries(
    xmlTree: etree._ElementTree, mainEltDesc: TEltDesc, targetOutElement: str = "entry"
) -> list[str]:
    """Serialisations of the source elements the mapping turns into ``targetOutElement``."""
    outList: list[str] = []

    def rec(context: etree._Element | etree._ElementTree, eltDesc: TEltDesc) -> None:
        for xmlElt in xpath_nodes(context, eltDesc.inSelector, eltDesc.namespaces):
            if eltDesc.outElement == targetOutElement:
                outList.append(etree.tostring(xmlElt, encoding="unicode"))
            elif eltDesc.children:
                for childDesc in eltDesc.children:
                    rec(xmlElt, childDesc)

    rec(xmlTree, mainEltDesc)
    return outList


def PruneMapping(
    mainEltDesc: TEltDesc, eltAndTextValuePairs: Iterable[tuple[str, str]]
) -> TEltDesc | None:
    """Keep only descriptors with a text value in ``eltAndTextValuePairs`` (and their ancestors)."""
    wanted = set(eltAndTextValuePairs)

    def prune(inEltDesc: TEltDesc) -> TEltDesc | None:
        newTextDescs = [
            t for t in inEltDesc.textVals or [] if (inEltDesc.outElement, t.outElement) in wanted
        ]
        newChildDescs = [c for c in (prune(ch) for ch in inEltDesc.children or []) if c]
        if not newChildDescs and not newTextDescs:
            return None
        out = TEltDesc(None)
        out.inSelector = inEltDesc.inSelector
        out.outElement = inEltDesc.outElement
        out.jsonPlural = inEltDesc.jsonPlural
        out.children = newChildDescs or None
        out.textVals = newTextDescs or None
        out.namespaces = inEltDesc.namespaces
        out.copyToOutElt = None
        return out

    return prune(mainEltDesc)


def ExtractTextValues(
    xmlTree: etree._ElementTree | etree._Element,
    mainEltDesc: TEltDesc,
    destDict: dict[tuple[str, str], set[str] | None],
) -> None:
    """Collect distinct raw values (before ``xlat``) of the requested (element, textVal) pairs."""
    if not destDict or mainEltDesc is None:
        return
    for key in list(destDict):
        if destDict[key] is None:
            destDict[key] = set()
    pruned = PruneMapping(mainEltDesc, destDict.keys())
    if pruned is None:
        return
    # Run the normal transformation without xlat and harvest values from the output.
    plain = _strip_xlat(pruned)
    results = _Transformer().process_elt(xmlTree, plain, None)

    def harvest(objs: list[JsonDict], desc: TEltDesc) -> None:
        for obj in objs:
            for t in desc.textVals or []:
                key = (desc.outElement, t.outElement)
                if key in destDict and t.outElement in obj:
                    target = destDict[key]
                    assert target is not None
                    target.add(str(obj[t.outElement]))
            for child in desc.children or []:
                harvest(obj.get(child.jsonPlural, []), child)

    harvest(results, plain)


def _strip_xlat(desc: TEltDesc) -> TEltDesc:
    out = TEltDesc(None)
    out.inSelector, out.outElement, out.jsonPlural = (
        desc.inSelector,
        desc.outElement,
        desc.jsonPlural,
    )
    out.namespaces, out.copyToOutElt = desc.namespaces, None
    out.children = [_strip_xlat(c) for c in desc.children or []] or None
    texts: list[TTextValDesc] = []
    for t in desc.textVals or []:
        clone = TTextValDesc({"attribute": t.attribute, "outElement": t.outElement})
        clone.inSelector, clone.namespaces, clone.constant = t.inSelector, t.namespaces, t.constant
        clone.regex, clone.compiledRegex, clone.regexGroup = t.regex, t.compiledRegex, t.regexGroup
        clone.markers, clone.xlat = None, None
        texts.append(clone)
    out.textVals = texts or None
    return out


def parse_document(source: str | Path | bytes) -> etree._ElementTree:
    """Parse a whole document safely (no DTD fetching, no entity expansion, huge trees allowed)."""
    parser = etree.XMLParser(
        load_dtd=False,
        no_network=True,
        resolve_entities=False,
        huge_tree=True,
        remove_blank_text=False,
    )
    if isinstance(source, bytes):
        return etree.ElementTree(etree.fromstring(source, parser))
    return etree.parse(str(source), parser)


def TransformEx(
    mappingJson: JsonDict | None = None,
    mappingEltDesc: TEltDesc | None = None,
    fnOrFileList: Iterable[str | Path] | str | Path | None = None,
    xmlStringList: Iterable[str | bytes] | None = None,
    treeList: Iterable[etree._ElementTree] | None = None,
) -> list[JsonDict]:
    """Transform one or more documents (paths, strings or parsed trees) into DMLex JSON objects.

    Whole-document transformation; use :mod:`elexifier_pipeline.xml.streaming` for large files.
    """
    if mappingEltDesc is None:
        if mappingJson is None:
            raise MappingError("no mapping provided")
        mappingEltDesc = TEltDesc(mappingJson)
    outJson: list[JsonDict] = []
    files: list[str | Path] = []
    if isinstance(fnOrFileList, str | Path):
        files = [fnOrFileList]
    elif fnOrFileList is not None:
        files = list(fnOrFileList)
    for fn in files:
        log.info("transforming %s", fn)
        outJson += TransformSingleXmlDoc(parse_document(fn), mappingEltDesc)
    for xmlString in xmlStringList or []:
        data = xmlString.encode("utf-8") if isinstance(xmlString, str) else xmlString
        outJson += TransformSingleXmlDoc(parse_document(data), mappingEltDesc)
    for tree in treeList or []:
        outJson += TransformSingleXmlDoc(tree, mappingEltDesc)
    return outJson
