type Node = Record<string, unknown>

const META = '{http://elex.is/wp1/teiLex0Mapper/meta}'
const str = (v: unknown) => (typeof v === 'string' ? v : '')
const list = (v: unknown): Node[] =>
  Array.isArray(v) ? v.filter((x): x is Node => typeof x === 'object' && x !== null) : []

function sourceOf(text: Node): string {
  const attribute = str(text.attribute)
  const where = text.inSelector ? ` of ${str(text.inSelector)}` : ''
  if (attribute === `${META}constant`) return `constant "${str(text.constant)}"`
  if (attribute === `${META}autogenerated`) return 'generated id'
  if (attribute === `${META}innerText`) return `text${where}`
  if (attribute === `${META}innerTextRec`) return `text (with descendants)${where}`
  return `@${attribute}${where}`
}

function Descriptor({ node, depth }: { node: Node; depth: number }) {
  const texts = list(node.textVals)
  const children = list(node.children)
  return (
    <li className="flex flex-col">
      <div className="flex flex-wrap items-baseline gap-x-2" style={{ paddingLeft: depth * 14 }}>
        <span className="font-medium">{str(node.outElement) || '?'}</span>
        <span className="text-muted-foreground">←</span>
        <code className="text-xs">{str(node.inSelector) || '?'}</code>
      </div>
      {texts.length > 0 && (
        <ul style={{ paddingLeft: depth * 14 + 14 }} className="text-muted-foreground text-xs">
          {texts.map((text, i) => (
            <li key={i} className="flex flex-wrap gap-x-1">
              <span className="text-foreground">.{str(text.outElement)}</span>
              <span>= {sourceOf(text)}</span>
              {text.regex ? <span>(regex {str(text.regex)})</span> : null}
              {text.xlat ? (
                <span>({Object.keys(text.xlat as object).length} value translations)</span>
              ) : null}
              {text.excludeSelector ? <span>(excluding {str(text.excludeSelector)})</span> : null}
              {list(text.markers).length > 0 ? (
                <span>({list(text.markers).length} markers)</span>
              ) : null}
            </li>
          ))}
        </ul>
      )}
      {children.length > 0 && (
        <ul className="flex flex-col gap-0.5">
          {children.map((child, i) => (
            <Descriptor key={i} node={child} depth={depth + 1} />
          ))}
        </ul>
      )}
    </li>
  )
}

/** Source path -> DMLex element tree of a mapping, computed from the JSON being edited. */
export function MappingTree({ spec }: { spec: Node | null }) {
  if (!spec) return <p className="text-muted-foreground p-3 text-xs">Not valid JSON yet.</p>
  return (
    <ul className="flex flex-col gap-1 p-3 text-sm">
      <Descriptor node={spec} depth={0} />
    </ul>
  )
}
