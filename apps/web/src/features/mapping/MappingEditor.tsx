import { PlayIcon, SaveIcon } from 'lucide-react'
import { useEffect, useMemo, useRef, useState } from 'react'
import { toast } from 'sonner'

import { Button } from '@/components/ui/button'
import { Input } from '@/components/ui/input'
import { formatMapping } from '@/features/mapping/formatMapping'
import { MappingTree } from '@/features/mapping/MappingTree'
import { CodeEditor } from '@/features/preview/CodeEditor'
import { ApiError } from '@/lib/api'
import { formatDate } from '@/lib/format'
import {
  useCheckMapping,
  useCreateRun,
  useMapping,
  useMappings,
  useSaveMapping,
} from '@/lib/queries'
import type { MappingIssue } from '@/lib/types'
import { usePreview } from '@/lib/uiActions'

const TEMPLATE = {
  inSelector: '/dictionary',
  outElement: 'lexicographicResource',
  textVals: [
    {
      attribute: '{http://elex.is/wp1/teiLex0Mapper/meta}constant',
      constant: 'http://example.org/my-dictionary',
      outElement: 'uri',
    },
    {
      attribute: '{http://elex.is/wp1/teiLex0Mapper/meta}constant',
      constant: 'en',
      outElement: 'langCode',
    },
  ],
  children: [
    {
      inSelector: 'entry',
      outElement: 'entry',
      textVals: [
        {
          inSelector: 'headword',
          attribute: '{http://elex.is/wp1/teiLex0Mapper/meta}innerText',
          outElement: 'headword',
        },
        { attribute: '{http://elex.is/wp1/teiLex0Mapper/meta}autogenerated', outElement: 'id' },
      ],
      children: [
        {
          inSelector: 'sense',
          outElement: 'sense',
          textVals: [
            { attribute: '{http://elex.is/wp1/teiLex0Mapper/meta}autogenerated', outElement: 'id' },
          ],
          children: [
            {
              inSelector: 'definition',
              outElement: 'definition',
              textVals: [
                {
                  attribute: '{http://elex.is/wp1/teiLex0Mapper/meta}innerText',
                  outElement: 'text',
                },
              ],
            },
          ],
        },
      ],
    },
  ],
}

function parseJson(text: string): Record<string, unknown> | null {
  try {
    const value: unknown = JSON.parse(text)
    return typeof value === 'object' && value !== null && !Array.isArray(value)
      ? (value as Record<string, unknown>)
      : null
  } catch {
    return null
  }
}

export function MappingEditor({
  projectId,
  version,
  canEdit,
}: {
  projectId: string
  version?: number
  canEdit: boolean
}) {
  const versions = useMappings(projectId)
  const mapping = useMapping(projectId, version ?? 'latest')
  const check = useCheckMapping(projectId)
  const save = useSaveMapping(projectId)
  const createRun = useCreateRun(projectId)
  const openMapping = usePreview((s) => s.openMapping)
  const openRun = usePreview((s) => s.openRun)

  const [text, setText] = useState<string | null>(null)
  const [note, setNote] = useState('')
  const [issues, setIssues] = useState<MappingIssue[]>([])
  const [checkedOk, setCheckedOk] = useState<boolean | null>(null)
  const loadedFor = useRef<string | null>(null)

  // load the editor when the (version of the) mapping changes; keep unsaved text otherwise
  useEffect(() => {
    if (mapping.isPending) return
    const key = mapping.data ? `${mapping.data.id}` : 'none'
    if (loadedFor.current === key) return
    loadedFor.current = key
    setText(formatMapping(mapping.data?.spec ?? TEMPLATE))
    setIssues(mapping.data?.issues ?? [])
    setCheckedOk(mapping.data ? !mapping.data.issues.some((i) => i.severity === 'error') : null)
    setNote('')
  }, [mapping.data, mapping.isPending])

  const parsed = useMemo(() => (text === null ? null : parseJson(text)), [text])
  const dirty = text !== null && text !== formatMapping(mapping.data?.spec ?? TEMPLATE)

  // debounced server-side check while typing
  const checkMutate = check.mutate
  useEffect(() => {
    if (!dirty || parsed === null) return
    const handle = setTimeout(() => {
      checkMutate(parsed, {
        onSuccess: (result) => {
          setIssues(result.issues)
          setCheckedOk(result.ok)
        },
      })
    }, 600)
    return () => clearTimeout(handle)
  }, [parsed, dirty, checkMutate])

  if (mapping.isPending || text === null)
    return <p className="text-muted-foreground p-3 text-sm">Loading mapping…</p>
  if (mapping.isError)
    return <p className="text-destructive p-3 text-sm">{mapping.error.message}</p>

  const current = mapping.data
  const errors = issues.filter((i) => i.severity === 'error')
  const canSave = canEdit && parsed !== null && dirty && errors.length === 0 && !save.isPending

  const onSave = () => {
    if (parsed === null) return
    save.mutate(
      { spec: parsed, note },
      {
        onSuccess: (saved) => {
          toast.success(`Mapping saved as version ${saved.version}`)
          loadedFor.current = null
          openMapping(saved.version)
        },
        onError: (error) => {
          const detail = error instanceof ApiError ? error.detail : error.message
          toast.error(detail)
        },
      },
    )
  }
  const onSample = () => {
    if (!current) return
    createRun.mutate(
      { kind: 'sample', mapping_version: current.version, n: 10, strategy: 'spread' },
      {
        onSuccess: (run) => openRun(run.id),
        onError: (error) => toast.error(error instanceof ApiError ? error.detail : error.message),
      },
    )
  }

  return (
    <div className="flex h-full flex-col">
      <div className="flex h-9 shrink-0 items-center gap-2 border-b px-3 text-xs">
        <span className="font-medium">Mapping</span>
        {versions.data && versions.data.length > 0 ? (
          <select
            aria-label="Mapping version"
            className="bg-background rounded border px-1 py-0.5"
            value={current?.version ?? ''}
            onChange={(e) => openMapping(Number(e.target.value))}
          >
            {versions.data.map((v) => (
              <option key={v.id} value={v.version}>
                v{v.version} · {formatDate(v.created_at)} · {v.source}
              </option>
            ))}
          </select>
        ) : (
          <span className="text-muted-foreground">no version yet, this is a template</span>
        )}
        {current?.note && (
          <span className="text-muted-foreground truncate" title={current.note}>
            {current.note}
          </span>
        )}
        <span className="ml-auto" />
        {current && (
          <Button
            variant="outline"
            size="xs"
            onClick={onSample}
            disabled={!canEdit || createRun.isPending || dirty}
            title={dirty ? 'Save first to sample with the edited mapping' : undefined}
          >
            <PlayIcon /> Run sample
          </Button>
        )}
        <Button size="xs" onClick={onSave} disabled={!canSave}>
          <SaveIcon /> Save as v{(versions.data?.[0]?.version ?? 0) + 1}
        </Button>
      </div>
      {canEdit && (
        <div className="flex shrink-0 items-center gap-2 border-b px-3 py-1.5 text-xs">
          <Input
            aria-label="Version note"
            placeholder="What changed and why (shown in the version history)"
            value={note}
            onChange={(e) => setNote(e.target.value)}
            className="h-7 text-xs"
          />
          <span className="text-muted-foreground shrink-0">
            {parsed === null
              ? 'invalid JSON'
              : check.isPending
                ? 'checking…'
                : checkedOk === false
                  ? `${errors.length} error(s)`
                  : dirty
                    ? 'unsaved changes'
                    : 'saved'}
          </span>
        </div>
      )}
      <div className="@container min-h-0 flex-1">
        <div className="grid h-full grid-cols-1 grid-rows-[3fr_2fr] @3xl:grid-cols-[3fr_2fr] @3xl:grid-rows-1">
          <div className="min-h-0 border-b @3xl:border-r @3xl:border-b-0">
            <CodeEditor
              value={text}
              onChange={setText}
              language="json"
              readOnly={!canEdit}
              ariaLabel="Mapping JSON"
            />
          </div>
          <div className="flex min-h-0 flex-col overflow-auto">
            {issues.length > 0 && (
              <ul className="flex flex-col gap-0.5 border-b px-3 py-2 text-xs">
                {issues.map((issue, i) => (
                  <li key={i} className="flex gap-1.5">
                    <span
                      className={`shrink-0 rounded px-1 ${
                        issue.severity === 'error'
                          ? 'bg-destructive/10 text-destructive'
                          : issue.severity === 'warning'
                            ? 'bg-amber-100 text-amber-900 dark:bg-amber-900/40 dark:text-amber-200'
                            : 'bg-muted text-muted-foreground'
                      }`}
                    >
                      {issue.severity}
                    </span>
                    <span>
                      <code className="text-muted-foreground mr-1">{issue.path}</code>
                      {issue.message}
                    </span>
                  </li>
                ))}
              </ul>
            )}
            <p className="text-muted-foreground bg-muted/40 border-b px-3 py-1 text-[11px] uppercase">
              Source → DMLex
            </p>
            <MappingTree spec={parsed} />
          </div>
        </div>
      </div>
    </div>
  )
}
