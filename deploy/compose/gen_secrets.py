#!/usr/bin/env python3
"""Print every secret the Compose stack needs, freshly generated, in ``.env`` form.

    make secrets            # or: python3 deploy/compose/gen_secrets.py

Standard library only, so it runs on a bare VM before anything is installed. Paste the output
into ``.env`` (replacing the dev values) before the first ``docker compose up``. The Compose
file refuses to start without ELX_SECRET_KEY and ELX_SESSION_SECRET; the others fall back to
the development defaults when missing, so set all of them.
"""

from __future__ import annotations

import base64
import secrets


def fernet_key() -> str:
    """What ``cryptography.fernet.Fernet.generate_key()`` returns: 32 random bytes, urlsafe
    base64 (44 characters)."""
    return base64.urlsafe_b64encode(secrets.token_bytes(32)).decode("ascii")


def main() -> None:
    lines = [
        "# Generated by deploy/compose/gen_secrets.py; keep this file out of version control.",
        "",
        "# Encrypts the lexicographers' provider API keys at rest. Never lose it: without it the",
        "# stored keys cannot be read. Rotation: put a new key first, keep the old one after a",
        "# comma until every credential has been re-saved.",
        f"ELX_SECRET_KEY={fernet_key()}",
        "# Signs the session cookie.",
        f"ELX_SESSION_SECRET={secrets.token_urlsafe(48)}",
        "",
        "# Database and identity provider.",
        f"POSTGRES_PASSWORD={secrets.token_hex(32)}",
        "KEYCLOAK_ADMIN=admin",
        f"KEYCLOAK_ADMIN_PASSWORD={secrets.token_hex(32)}",
        "# Also set on the Keycloak client elexifier-web (realm elexifier > Clients >",
        "# Credentials), or in deploy/compose/keycloak/realm-elexifier.json before the first start.",
        f"OIDC_CLIENT_SECRET={secrets.token_hex(32)}",
        "",
        "# Object storage (Garage). The access key id must be GK + 24 hex characters and the",
        "# secret 64 hex characters: garage-init imports exactly these on the first start.",
        f"S3_ACCESS_KEY=GK{secrets.token_hex(12)}",
        f"S3_SECRET_KEY={secrets.token_hex(32)}",
        f"GARAGE_ADMIN_TOKEN={secrets.token_hex(32)}",
        "",
        "# API <-> sandbox runner.",
        f"SANDBOX_RUNNER_TOKEN={secrets.token_hex(32)}",
        "",
        "# Not secrets, but production needs them too:",
        "ELX_ENABLE_TEST_MODEL=0",
        "# SITE_URL=https://dictionaries.example.org",
        "# SITE_ADDRESS=dictionaries.example.org",
        "# KEYCLOAK_URL=https://auth.example.org",
    ]
    print("\n".join(lines))


if __name__ == "__main__":
    main()
